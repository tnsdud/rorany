-- (1) profiles: 회원 프로필 (auth.users 연동)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    full_name TEXT,
    avatar_url TEXT,
    phone TEXT,
    grade TEXT NOT NULL DEFAULT 'BRONZE' CHECK (grade IN ('BRONZE', 'SILVER', 'GOLD', 'VIP')),
    total_spent BIGINT NOT NULL DEFAULT 0 CHECK (total_spent >= 0),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    points BIGINT NOT NULL DEFAULT 0 CHECK (points >= 0),
    admin_memo TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.profiles
    ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'suspended')),
    ADD COLUMN IF NOT EXISTS points BIGINT NOT NULL DEFAULT 0 CHECK (points >= 0),
    ADD COLUMN IF NOT EXISTS admin_memo TEXT NOT NULL DEFAULT '';

-- (2) categories: 상품 카테고리
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    parent_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- (3) products: 상품 기본 정보
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    slug TEXT UNIQUE,
    description TEXT,
    price INT NOT NULL CHECK (price >= 0),
    sale_price INT CHECK (sale_price >= 0 AND sale_price <= price),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- (4) product_options: 상품 옵션 및 재고
CREATE TABLE IF NOT EXISTS public.product_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    color TEXT,
    size TEXT,
    extra_price INT NOT NULL DEFAULT 0,
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    safe_stock INT NOT NULL DEFAULT 5 CHECK (safe_stock >= 0),
    sku TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.product_options
    ADD COLUMN IF NOT EXISTS safe_stock INT NOT NULL DEFAULT 5 CHECK (safe_stock >= 0);

-- (5) product_images: 상품 이미지
CREATE TABLE IF NOT EXISTS public.product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    is_thumbnail BOOLEAN NOT NULL DEFAULT false,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- (6) carts: 장바구니
CREATE TABLE IF NOT EXISTS public.carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    option_id BIGINT REFERENCES public.product_options(id) ON DELETE CASCADE,
    quantity INT NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_user_product_option UNIQUE NULLS NOT DISTINCT (user_id, product_id, option_id)
);

-- (7) orders: 주문 내역
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_number TEXT NOT NULL UNIQUE,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'pending' 
        CHECK (status IN ('pending', 'paid', 'preparing', 'shipping', 'delivered', 'cancelled', 'refunded')),
    total_amount INT NOT NULL CHECK (total_amount >= 0),
    discount_amount INT NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    shipping_fee INT NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
    final_amount INT NOT NULL CHECK (final_amount >= 0),
    recipient_name TEXT NOT NULL,
    recipient_phone TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    shipping_memo TEXT,
    payment_method TEXT,
    payment_key TEXT,
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- (8) order_items: 주문 상품 상세
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    option_id BIGINT REFERENCES public.product_options(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    option_info TEXT,
    price INT NOT NULL CHECK (price >= 0),
    quantity INT NOT NULL CHECK (quantity > 0),
    subtotal INT NOT NULL CHECK (subtotal >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- (9) refunds: 환불 요청 및 관리
CREATE TABLE IF NOT EXISTS public.refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    order_item_id BIGINT REFERENCES public.order_items(id) ON DELETE SET NULL,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'requested' 
        CHECK (status IN ('requested', 'approved', 'rejected', 'completed')),
    request_type TEXT NOT NULL DEFAULT 'return' CHECK (request_type IN ('return', 'exchange')),
    reason TEXT NOT NULL,
    customer_request TEXT NOT NULL DEFAULT '',
    requested_option TEXT,
    requested_option_id BIGINT REFERENCES public.product_options(id) ON DELETE SET NULL,
    refund_amount INT NOT NULL CHECK (refund_amount >= 0),
    collection_status TEXT NOT NULL DEFAULT 'pending' CHECK (collection_status IN ('pending', 'completed')),
    inspection_status TEXT NOT NULL DEFAULT 'pending' CHECK (inspection_status IN ('pending', 'completed')),
    refund_status TEXT NOT NULL DEFAULT 'pending' CHECK (refund_status IN ('pending', 'completed')),
    redelivery_status TEXT NOT NULL DEFAULT 'pending' CHECK (redelivery_status IN ('pending', 'shipped')),
    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.refunds
    ADD COLUMN IF NOT EXISTS request_type TEXT NOT NULL DEFAULT 'return'
        CHECK (request_type IN ('return', 'exchange')),
    ADD COLUMN IF NOT EXISTS customer_request TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS requested_option TEXT,
    ADD COLUMN IF NOT EXISTS requested_option_id BIGINT REFERENCES public.product_options(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS collection_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (collection_status IN ('pending', 'completed')),
    ADD COLUMN IF NOT EXISTS inspection_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (inspection_status IN ('pending', 'completed')),
    ADD COLUMN IF NOT EXISTS refund_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (refund_status IN ('pending', 'completed')),
    ADD COLUMN IF NOT EXISTS redelivery_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (redelivery_status IN ('pending', 'shipped'));

CREATE TABLE IF NOT EXISTS public.inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    option_id BIGINT REFERENCES public.product_options(id) ON DELETE SET NULL,
    order_id UUID REFERENCES public.orders(id) ON DELETE SET NULL,
    order_item_id BIGINT REFERENCES public.order_items(id) ON DELETE SET NULL,
    refund_id BIGINT REFERENCES public.refunds(id) ON DELETE SET NULL,
    movement_type TEXT NOT NULL CHECK (movement_type IN ('order', 'cancel_restock', 'return_restock', 'exchange_restock', 'exchange_out', 'adjustment')),
    quantity INT NOT NULL CHECK (quantity <> 0),
    reason TEXT NOT NULL DEFAULT '',
    event_key TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

