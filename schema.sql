-- (2) auth.users 신규 생성 시 profiles 자동 생성 트리거 (소셜 로그인 포함)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    extracted_name TEXT;
    extracted_avatar TEXT;
BEGIN
    -- 소셜 로그인(Google, Kakao, Github 등) 및 이메일 회원가입 메타데이터 파싱
    extracted_name := COALESCE(
        NEW.raw_user_meta_data->>'full_name',
        NEW.raw_user_meta_data->>'name',
        NEW.raw_user_meta_data->>'user_name',
        split_part(NEW.email, '@', 1)
    );

    extracted_avatar := COALESCE(
        NEW.raw_user_meta_data->>'avatar_url',
        NEW.raw_user_meta_data->>'picture',
        ''
    );

    INSERT INTO public.profiles (
        id,
        email,
        full_name,
        avatar_url,
        grade,
        total_spent,
        role
    ) VALUES (
        NEW.id,
        NEW.email,
        extracted_name,
        extracted_avatar,
        'BRONZE',
        0,
        'customer'
    )
    ON CONFLICT (id) DO UPDATE SET
        email = EXCLUDED.email,
        full_name = COALESCE(public.profiles.full_name, EXCLUDED.full_name),
        avatar_url = COALESCE(public.profiles.avatar_url, EXCLUDED.avatar_url);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- auth.users에 트리거 등록
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- (3) 고객 등급 자동 업데이트 함수 (누적 실 결제금액 기준)
-- 기준: VIP(100만원 이상), GOLD(30만원 이상), SILVER(10만원 이상), BRONZE(기본)
CREATE OR REPLACE FUNCTION public.update_customer_grade(target_user_id UUID)
RETURNS VOID AS $$
DECLARE
    spent_sum BIGINT := 0;
    new_grade TEXT := 'BRONZE';
BEGIN
    IF target_user_id IS NULL THEN
        RETURN;
    END IF;

    -- 결제 완료/배송/배송완료 상태인 주문의 총 실결제 금액 합산 (취소/환불 제외)
    SELECT COALESCE(SUM(final_amount), 0)
    INTO spent_sum
    FROM public.orders
    WHERE user_id = target_user_id
      AND status IN ('paid', 'preparing', 'shipping', 'delivered');

    -- 환불 완료된 금액 차감
    spent_sum := spent_sum - COALESCE((
        SELECT SUM(refund_amount)
        FROM public.refunds
        WHERE user_id = target_user_id
          AND status = 'completed'
    ), 0);

    IF spent_sum < 0 THEN
        spent_sum := 0;
    END IF;

    -- 등급 산정
    IF spent_sum >= 1000000 THEN
        new_grade := 'VIP';
    ELSIF spent_sum >= 300000 THEN
        new_grade := 'GOLD';
    ELSIF spent_sum >= 100000 THEN
        new_grade := 'SILVER';
    ELSE
        new_grade := 'BRONZE';
    END IF;

    -- 프로필 테이블 갱신
    UPDATE public.profiles
    SET total_spent = spent_sum,
        grade = new_grade,
        updated_at = timezone('utc'::text, now())
    WHERE id = target_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- (4) 주문 및 환불 상태 변경 시 고객 등급 자동 갱신 트리거 함수
CREATE OR REPLACE FUNCTION public.trigger_customer_grade_sync()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_TABLE_NAME = 'orders' THEN
        -- 주문 유저 등급 갱신
        IF NEW.user_id IS NOT NULL THEN
            PERFORM public.update_customer_grade(NEW.user_id);
        END IF;
        IF OLD.user_id IS NOT NULL AND OLD.user_id <> NEW.user_id THEN
            PERFORM public.update_customer_grade(OLD.user_id);
        END IF;
    ELSIF TG_TABLE_NAME = 'refunds' THEN
        -- 환불 관련 유저 등급 갱신
        IF NEW.user_id IS NOT NULL THEN
            PERFORM public.update_customer_grade(NEW.user_id);
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.apply_order_item_inventory()
RETURNS TRIGGER AS $$
DECLARE
    product_option_product_id BIGINT;
BEGIN
    IF NEW.option_id IS NULL THEN
        RETURN NEW;
    END IF;

    UPDATE public.product_options
    SET stock_quantity = stock_quantity - NEW.quantity
    WHERE id = NEW.option_id
      AND stock_quantity >= NEW.quantity
    RETURNING product_id INTO product_option_product_id;

    IF product_option_product_id IS NULL THEN
        RAISE EXCEPTION '상품 재고가 부족하거나 옵션을 찾을 수 없습니다.';
    END IF;

    INSERT INTO public.inventory_movements (
        product_id, option_id, order_id, order_item_id, movement_type, quantity, reason, event_key
    ) VALUES (
        product_option_product_id, NEW.option_id, NEW.order_id, NEW.id, 'order', -NEW.quantity,
        '주문 출고', 'order-item:' || NEW.id::TEXT
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.restore_cancelled_order_inventory()
RETURNS TRIGGER AS $$
DECLARE
    order_line RECORD;
BEGIN
    IF NEW.status = 'cancelled' AND OLD.status IN ('pending', 'paid', 'preparing') THEN
        FOR order_line IN
            SELECT id, product_id, option_id, quantity
            FROM public.order_items
            WHERE order_id = NEW.id AND option_id IS NOT NULL
        LOOP
            UPDATE public.product_options
            SET stock_quantity = stock_quantity + order_line.quantity
            WHERE id = order_line.option_id;

            INSERT INTO public.inventory_movements (
                product_id, option_id, order_id, order_item_id, movement_type, quantity, reason, event_key
            ) VALUES (
                order_line.product_id, order_line.option_id, NEW.id, order_line.id, 'cancel_restock',
                order_line.quantity, '주문 취소 재입고', 'cancel-order-item:' || order_line.id::TEXT
            ) ON CONFLICT (event_key) DO NOTHING;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.apply_return_inventory()
RETURNS TRIGGER AS $$
DECLARE
    order_line RECORD;
    target_product_id BIGINT;
BEGIN
    IF NEW.status <> 'approved' THEN
        RETURN NEW;
    END IF;

    IF NEW.inspection_status = 'completed' AND OLD.inspection_status <> 'completed' THEN
        FOR order_line IN
            SELECT id, product_id, option_id, quantity
            FROM public.order_items
            WHERE order_id = NEW.order_id
              AND option_id IS NOT NULL
              AND (NEW.order_item_id IS NULL OR id = NEW.order_item_id)
        LOOP
            UPDATE public.product_options
            SET stock_quantity = stock_quantity + order_line.quantity
            WHERE id = order_line.option_id;

            INSERT INTO public.inventory_movements (
                product_id, option_id, order_id, order_item_id, refund_id, movement_type, quantity, reason, event_key
            ) VALUES (
                order_line.product_id, order_line.option_id, NEW.order_id, order_line.id, NEW.id,
                CASE WHEN NEW.request_type = 'exchange' THEN 'exchange_restock' ELSE 'return_restock' END,
                order_line.quantity, '반품 상품 검수 후 입고', 'return-restock:' || NEW.id::TEXT || ':' || order_line.id::TEXT
            ) ON CONFLICT (event_key) DO NOTHING;
        END LOOP;
    END IF;

    IF NEW.request_type = 'exchange'
       AND NEW.redelivery_status = 'shipped'
       AND OLD.redelivery_status <> 'shipped' THEN
        IF NEW.requested_option_id IS NULL THEN
            RAISE EXCEPTION '재배송할 교환 옵션을 선택해 주세요.';
        END IF;

        UPDATE public.product_options
        SET stock_quantity = stock_quantity - 1
        WHERE id = NEW.requested_option_id
          AND stock_quantity > 0
        RETURNING product_id INTO target_product_id;

        IF target_product_id IS NULL THEN
            RAISE EXCEPTION '교환 상품 재고가 부족합니다.';
        END IF;

        INSERT INTO public.inventory_movements (
            product_id, option_id, order_id, refund_id, movement_type, quantity, reason, event_key
        ) VALUES (
            target_product_id, NEW.requested_option_id, NEW.order_id, NEW.id, 'exchange_out', -1,
            '교환 상품 재배송', 'exchange-out:' || NEW.id::TEXT
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.adjust_inventory(
    target_option_id BIGINT,
    quantity_delta INT,
    adjustment_reason TEXT,
    movement_event_key TEXT
)
RETURNS JSONB AS $$
DECLARE
    target_product_id BIGINT;
    updated_option JSONB;
BEGIN
    IF quantity_delta = 0 THEN
        RAISE EXCEPTION '재고 변경 수량은 0일 수 없습니다.';
    END IF;

    UPDATE public.product_options
    SET stock_quantity = stock_quantity + quantity_delta
    WHERE id = target_option_id
      AND stock_quantity + quantity_delta >= 0
    RETURNING product_id, to_jsonb(product_options) INTO target_product_id, updated_option;

    IF target_product_id IS NULL THEN
        RAISE EXCEPTION '재고가 부족하거나 옵션을 찾을 수 없습니다.';
    END IF;

    INSERT INTO public.inventory_movements (
        product_id, option_id, movement_type, quantity, reason, event_key
    ) VALUES (
        target_product_id, target_option_id, 'adjustment', quantity_delta,
        COALESCE(adjustment_reason, ''), movement_event_key
    );
    RETURN updated_option;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

REVOKE ALL ON FUNCTION public.adjust_inventory(BIGINT, INT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.adjust_inventory(BIGINT, INT, TEXT, TEXT) TO service_role;

