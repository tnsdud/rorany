ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.refunds ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

-- 1) profiles 정책: 본인 프로필 조회/수정 가능, 전체 공개 프로필 조회 허용
CREATE POLICY "프로필 조회는 모든 사용자 가능" 
    ON public.profiles FOR SELECT USING (true);

CREATE POLICY "본인 프로필만 수정 가능" 
    ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- 2) categories, products, product_options, product_images: 모든 사용자 조회 가능
CREATE POLICY "카테고리 누구나 조회 가능" 
    ON public.categories FOR SELECT USING (true);

CREATE POLICY "상품 정보 누구나 조회 가능" 
    ON public.products FOR SELECT USING (is_active = true);

CREATE POLICY "상품 옵션 누구나 조회 가능" 
    ON public.product_options FOR SELECT USING (true);

CREATE POLICY "상품 이미지 누구나 조회 가능" 
    ON public.product_images FOR SELECT USING (true);

-- 3) carts: 본인 장바구니만 CRUD 가능
CREATE POLICY "본인 장바구니만 접근 가능" 
    ON public.carts FOR ALL USING (auth.uid() = user_id);

-- 4) orders & order_items: 본인 주문만 조회/생성 가능
CREATE POLICY "본인 주문만 조회 가능" 
    ON public.orders FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "본인 주문만 생성 가능" 
    ON public.orders FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "본인 주문 상세만 조회 가능" 
    ON public.order_items FOR SELECT USING (
        EXISTS (
            SELECT 1 FROM public.orders 
            WHERE orders.id = order_items.order_id 
              AND orders.user_id = auth.uid()
        )
    );

-- 5) refunds: 본인 환불 요청만 조회/생성 가능
CREATE POLICY "본인 환불 내역 조회 가능" 
    ON public.refunds FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "본인 환불 요청 생성 가능" 
    ON public.refunds FOR INSERT WITH CHECK (auth.uid() = user_id);

-- 6) notifications: 본인 알림만 조회/수정(읽음 처리) 가능
CREATE POLICY "본인 알림만 접근 가능" 
    ON public.notifications FOR ALL USING (auth.uid() = user_id);

-- 7) reviews: 누구나 조회 가능, 작성/수정/삭제는 본인만 가능
CREATE POLICY "리뷰 누구나 조회 가능" 
    ON public.reviews FOR SELECT USING (true);

CREATE POLICY "본인 리뷰만 등록 가능" 
    ON public.reviews FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "본인 리뷰만 수정/삭제 가능" 
    ON public.reviews FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "본인 리뷰만 삭제 가능" 
    ON public.reviews FOR DELETE USING (auth.uid() = user_id);
